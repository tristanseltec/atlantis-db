//! Identifier types: [`Uuid`] and [`Ulid`].
//!
//! Both are 128-bit identifiers implemented without external dependencies.
//! Randomness comes from the standard library's per-process random hasher
//! keys, which is suitable for unique identifiers but not for cryptography.

use std::collections::hash_map::RandomState;
use std::fmt;
use std::hash::{BuildHasher, Hasher};
use std::str::FromStr;
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Mutex;
use std::time::{SystemTime, UNIX_EPOCH};

use serde::{Deserialize, Serialize};

use crate::AtlantisError;

/// Returns 64 non-cryptographic random bits.
pub(crate) fn random_u64() -> u64 {
    static COUNTER: AtomicU64 = AtomicU64::new(0);
    let mut hasher = RandomState::new().build_hasher();
    hasher.write_u64(COUNTER.fetch_add(1, Ordering::Relaxed));
    hasher.write_u128(
        SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or(0),
    );
    hasher.finish()
}

fn unix_millis() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_millis() as u64)
        .unwrap_or(0)
}

/// A 128-bit universally unique identifier (RFC 9562).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct Uuid(pub [u8; 16]);

impl Uuid {
    /// Generates a random version 4 UUID.
    pub fn new_v4() -> Self {
        let hi = random_u64().to_be_bytes();
        let lo = random_u64().to_be_bytes();
        let mut b = [0u8; 16];
        b[..8].copy_from_slice(&hi);
        b[8..].copy_from_slice(&lo);
        b[6] = (b[6] & 0x0f) | 0x40; // version 4
        b[8] = (b[8] & 0x3f) | 0x80; // RFC variant
        Uuid(b)
    }

    /// Returns the raw bytes.
    pub fn as_bytes(&self) -> &[u8; 16] {
        &self.0
    }
}

impl fmt::Display for Uuid {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        for (i, byte) in self.0.iter().enumerate() {
            if matches!(i, 4 | 6 | 8 | 10) {
                f.write_str("-")?;
            }
            write!(f, "{byte:02x}")?;
        }
        Ok(())
    }
}

impl FromStr for Uuid {
    type Err = AtlantisError;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let hex: String = s.chars().filter(|c| *c != '-').collect();
        let dashes_ok = s.len() == 32
            || (s.len() == 36 && [8, 13, 18, 23].iter().all(|&i| s.as_bytes()[i] == b'-'));
        if hex.len() != 32 || !dashes_ok {
            return Err(AtlantisError::InvalidValue(format!("invalid uuid: {s}")));
        }
        let mut b = [0u8; 16];
        for (i, slot) in b.iter_mut().enumerate() {
            *slot = u8::from_str_radix(&hex[i * 2..i * 2 + 2], 16)
                .map_err(|_| AtlantisError::InvalidValue(format!("invalid uuid: {s}")))?;
        }
        Ok(Uuid(b))
    }
}

const CROCKFORD: &[u8; 32] = b"0123456789ABCDEFGHJKMNPQRSTVWXYZ";

/// A Universally Unique Lexicographically Sortable Identifier.
///
/// 48 bits of millisecond timestamp followed by 80 random bits. ULIDs
/// generated by one process are strictly increasing, so records created with
/// generated keys are stored in creation order. This is the default record
/// key kind.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
pub struct Ulid(pub u128);

impl Ulid {
    /// Generates a new ULID, monotonic within this process.
    pub fn new() -> Self {
        static LAST: Mutex<u128> = Mutex::new(0);
        let random = ((random_u64() as u128) << 64 | random_u64() as u128) & ((1u128 << 80) - 1);
        let candidate = (unix_millis() as u128) << 80 | random;
        let mut last = LAST.lock().unwrap_or_else(|e| e.into_inner());
        let next = if candidate > *last {
            candidate
        } else {
            *last + 1
        };
        *last = next;
        Ulid(next)
    }

    /// Returns the millisecond Unix timestamp embedded in the ULID.
    pub fn timestamp_ms(&self) -> u64 {
        (self.0 >> 80) as u64
    }
}

impl Default for Ulid {
    fn default() -> Self {
        Self::new()
    }
}

impl fmt::Display for Ulid {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let mut out = [0u8; 26];
        for (i, slot) in out.iter_mut().enumerate() {
            let shift = 5 * (25 - i);
            *slot = CROCKFORD[((self.0 >> shift) & 0x1f) as usize];
        }
        f.write_str(std::str::from_utf8(&out).expect("crockford alphabet is ascii"))
    }
}

impl FromStr for Ulid {
    type Err = AtlantisError;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let err = || AtlantisError::InvalidValue(format!("invalid ulid: {s}"));
        if s.len() != 26 {
            return Err(err());
        }
        let mut value: u128 = 0;
        for (i, c) in s.bytes().enumerate() {
            let digit = CROCKFORD
                .iter()
                .position(|&a| a == c.to_ascii_uppercase())
                .ok_or_else(err)? as u128;
            // The first character carries only 3 bits (128 = 26 * 5 - 2).
            if i == 0 && digit > 7 {
                return Err(err());
            }
            value = (value << 5) | digit;
        }
        Ok(Ulid(value))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn uuid_roundtrip_and_version() {
        let u = Uuid::new_v4();
        assert_eq!(u.0[6] >> 4, 4);
        let text = u.to_string();
        assert_eq!(text.len(), 36);
        assert_eq!(text.parse::<Uuid>().unwrap(), u);
        assert!("not-a-uuid".parse::<Uuid>().is_err());
    }

    #[test]
    fn uuids_are_distinct() {
        let a = Uuid::new_v4();
        let b = Uuid::new_v4();
        assert_ne!(a, b);
    }

    #[test]
    fn ulid_roundtrip() {
        let u = Ulid::new();
        let text = u.to_string();
        assert_eq!(text.len(), 26);
        assert_eq!(text.parse::<Ulid>().unwrap(), u);
        assert_eq!(text.to_lowercase().parse::<Ulid>().unwrap(), u);
    }

    #[test]
    fn ulids_are_monotonic_and_sort_like_their_text() {
        let ids: Vec<Ulid> = (0..1000).map(|_| Ulid::new()).collect();
        for pair in ids.windows(2) {
            assert!(pair[0] < pair[1]);
            assert!(pair[0].to_string() < pair[1].to_string());
        }
    }

    #[test]
    fn ulid_rejects_bad_input() {
        assert!("too-short".parse::<Ulid>().is_err());
        assert!("8ZZZZZZZZZZZZZZZZZZZZZZZZZ".parse::<Ulid>().is_err()); // overflow
        assert!("0123456789ABCDEFGHJKMNPQRU".parse::<Ulid>().is_err()); // 'U' not in alphabet
    }
}
